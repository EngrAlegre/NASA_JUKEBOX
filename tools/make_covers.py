#!/usr/bin/env python3
"""
Regenerate record covers.

A record sleeve should show the side at its most legible, not whatever frame
happens to sit in the middle of the sequence. This picks the frame with the
highest mean luminance and writes it as the cover, keeping the original
filename so the catalog does not change.

    python tools/make_covers.py
"""

import glob
import json
import os

from PIL import Image, ImageStat

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")


def brightness(path: str) -> float:
    im = Image.open(path).convert("RGB")
    return sum(ImageStat.Stat(im).mean) / 3


def main() -> None:
    catalog_path = os.path.join(DATA, "records.json")
    catalog = json.load(open(catalog_path, encoding="utf-8"))

    for rec in catalog["records"]:
        rid = rec["id"]
        folder = os.path.join(DATA, "records", rid)
        frames = sorted(glob.glob(os.path.join(folder, "f*.jpg")) + glob.glob(os.path.join(folder, "f*.png")))
        if not frames:
            continue

        best = max(frames, key=brightness)
        ext = os.path.splitext(rec.get("cover", "cover.jpg"))[1] or ".jpg"
        dest = os.path.join(folder, "cover" + ext)

        im = Image.open(best)
        if im.mode == "RGBA":
            # flatten onto the page's near-black so the sleeve looks like the deck
            flat = Image.new("RGB", im.size, (7, 8, 12))
            flat.paste(im, (0, 0), im)
            im = flat
        else:
            im = im.convert("RGB")

        width = 760
        height = max(1, round(im.height * width / im.width))
        im = im.resize((width, height), Image.LANCZOS)
        im.save(dest, quality=86, optimize=True)

        rec["cover"] = f"records/{rid}/cover{ext}"
        print(f"{rid:<12} {os.path.basename(best)}  {brightness(best):.1f}  -> {os.path.basename(dest)}")

    json.dump(catalog, open(catalog_path, "w", encoding="utf-8"), indent=2)
    with open(os.path.join(DATA, "records.js"), "w", encoding="utf-8") as fh:
        fh.write("/* generated by tools/build_library.py — do not edit */\nwindow.JUKEBOX_DATA = ")
        json.dump(catalog, fh, indent=2)
        fh.write(";\n")
    print("catalog updated")


if __name__ == "__main__":
    main()
