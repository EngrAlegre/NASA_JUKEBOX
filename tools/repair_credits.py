#!/usr/bin/env python3
"""
Re-parse the SVS credit blocks for records that are already on disk.

The first pass at credit extraction required the role label to sit flush against
its tags; the real pages indent it. This repairs the catalog without re-downloading
anything, and is safe to re-run.

    python tools/repair_credits.py
"""

import html
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, ".cache")
DATA = os.path.join(ROOT, "data")

ROLES = ["Visualizer", "Scientists", "Producer", "Technical support", "Writer",
         "Data provider", "Designer", "Animator", "Web developer", "Scientist"]


def strip_tags(s: str) -> str:
    s = re.sub(r"<[^>]+>", " ", s)
    return re.sub(r"\s+", " ", html.unescape(s)).strip()


def parse_roles(page: str):
    found = []
    label_re = "|".join(ROLES)
    for m in re.finditer(rf">\s*({label_re})\s*<", page):
        role = m.group(1)
        tail = page[m.start(): m.start() + 6000]
        # cut at the next role label so names never bleed across sections
        nxt = re.search(rf">\s*({label_re})\s*<", tail[10:])
        chunk = tail[: nxt.start() + 10] if nxt else tail[:2500]
        names = []
        for nm in re.findall(r"<a[^>]*>\s*([^<]{2,60}?)\s*</a>", chunk):
            nm = html.unescape(nm).strip()
            if nm and nm not in names and not nm.startswith("<") and not nm.startswith("http"):
                names.append(nm)
        if names and not any(f["role"] == role for f in found):
            found.append({"role": role, "names": names[:6]})
    return found


def main() -> None:
    path = os.path.join(DATA, "records.json")
    catalog = json.load(open(path, encoding="utf-8"))

    for rec in catalog["records"]:
        url = rec["source"].get("url", "")
        m = re.search(r"svs\.gsfc\.nasa\.gov/(\d+)/", url)
        if not m:
            continue
        page_path = os.path.join(CACHE, f"svs_{m.group(1)}.html")
        if not os.path.exists(page_path):
            continue
        page = open(page_path, encoding="utf-8", errors="ignore").read()

        roles = parse_roles(page)
        credit = re.search(r"Please give credit for this item to:\s*(?:<[^>]+>\s*)*([^<]{3,160})", page)
        if credit:
            rec["source"]["credit"] = html.unescape(credit.group(1)).strip()
        rec["source"]["roles"] = roles
        print(f"{rec['id']:<12} {len(roles)} roles  " + ", ".join(f"{r['role']}: {', '.join(r['names'][:2])}" for r in roles))

    json.dump(catalog, open(path, "w", encoding="utf-8"), indent=2)
    with open(os.path.join(DATA, "records.js"), "w", encoding="utf-8") as fh:
        fh.write("/* generated by tools/build_library.py — do not edit */\nwindow.JUKEBOX_DATA = ")
        json.dump(catalog, fh, indent=2)
        fh.write(";\n")
    print("catalog updated")


if __name__ == "__main__":
    main()
